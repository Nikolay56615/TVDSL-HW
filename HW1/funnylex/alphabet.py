"""Алфавит автомата.

Символы 0..127 - коды ASCII. Символ 128 (OTHER) - «любой не-ASCII символ»:
сканер подставляет его вместо букв вроде 'ё' или '→'. Ни одно правило в
tokens.spec не содержит OTHER, поэтому по нему автомат всегда уходит в ловушку.
"""

OTHER = 128
SIZE = 129                      # число символов алфавита


def symbol(ch):
    """Символ текста -> символ алфавита автомата (0..128)."""
    code = ord(ch)
    return code if code < OTHER else OTHER
